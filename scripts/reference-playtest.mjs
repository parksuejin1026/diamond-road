import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('artifacts/reference', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on('pageerror', error => console.log('PAGE ERROR', error.message));
page.on('requestfailed', request => console.log('REQUEST FAILED', request.url(), request.failure()?.errorText));
await page.goto('https://kickru.com/', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => !document.body.innerText.includes('커리어를 불러오고 있어요'), { timeout: 25000 }).catch(() => console.log('LOADING DID NOT FINISH'));
console.log('URL', page.url());
await page.screenshot({ path: 'artifacts/reference/start.png', fullPage: true });
const confirm = page.getByRole('button', { name: '확인', exact: true });
if (await confirm.isVisible()) await confirm.click();
await page.waitForTimeout(500);
console.log('AFTER NOTICE', (await page.locator('body').innerText()).slice(-5000));
console.log('AFTER NOTICE BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await page.getByRole('button', { name: '새로운 인생 시작하기', exact: true }).click();
await page.waitForTimeout(1000);
console.log('CREATE SCREEN', (await page.locator('body').innerText()).slice(0, 14000));
console.log('INPUTS', JSON.stringify(await page.locator('input,select').evaluateAll(nodes => nodes.map(n => ({ tag: n.tagName, type: n.type, placeholder: n.placeholder, value: n.value, name: n.name })))));
console.log('CREATE BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.screenshot({ path: 'artifacts/reference/create.png', fullPage: true });
await page.getByRole('button', { name: '이 아바타로 할게요', exact: true }).click();
await page.waitForTimeout(300);
console.log('PROFILE', (await page.locator('body').innerText()).slice(0, 10000));
console.log('PROFILE INPUTS', JSON.stringify(await page.locator('input,select').evaluateAll(nodes => nodes.map(n => ({ tag: n.tagName, type: n.type, placeholder: n.placeholder, value: n.value, name: n.name })))));
console.log('PROFILE BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.locator('input').first().fill('플레이테스트');
await page.getByRole('button', { name: '다음', exact: true }).click();
await page.waitForTimeout(300);
console.log('CANDIDATES', (await page.locator('body').innerText()).slice(0, 12000));
console.log('CANDIDATE BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.getByRole('button', { name: '이 스타일로 할게요', exact: true }).click();
await page.waitForTimeout(500);
console.log('CAREER', (await page.locator('body').innerText()).slice(0, 14000));
console.log('CAREER BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.getByRole('button', { name: /^슈팅/ }).click();
await page.getByRole('button', { name: '선수 만들기', exact: true }).click();
await page.waitForTimeout(500);
console.log('FIRST SEASON', (await page.locator('body').innerText()).slice(0, 13000));
console.log('FIRST SEASON BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.getByRole('button', { name: '고1 시즌 시작', exact: true }).click();
await page.waitForTimeout(500);
console.log('PLAY DASHBOARD', (await page.locator('body').innerText()).slice(0, 14000));
console.log('PLAY BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.screenshot({ path: 'artifacts/reference/first-season.png', fullPage: true });
const skip = page.getByRole('button', { name: '건너뛰기', exact: true });
if (await skip.isVisible()) await skip.click();
await page.waitForTimeout(2000);
console.log('SEASON RESULT', (await page.locator('body').innerText()).slice(0, 13000));
console.log('RESULT BUTTONS', JSON.stringify(await page.getByRole('button').allTextContents()));
await page.screenshot({ path: 'artifacts/reference/season-result.png', fullPage: true });
await page.screenshot({ path: 'artifacts/reference/career.png', fullPage: true });
await browser.close();
