import { expect, it } from 'vitest';
import { createCareer } from '../engine/career';
import { simulateAsianGames, isAsianGamesYear } from '../engine/asianGames';
import { SCHOOLS } from '../engine/schools';
for (const role of ['HITTER', 'PITCHER'] as const) it(`${role}의 국가대표 대회는 정규 기록과 분리하고 같은 해에 중복 실행하지 않는다`, () => {
  const save = createCareer({ name: '대표 선수', role, teamId: 'lg', hand: 'RIGHT', position: role === 'HITTER' ? 'RF' : undefined }, 12);
  save.year = 2030; save.player.age = 22; save.player.rosterStatus = 'STARTER';
  for (const key of Object.keys(save.player.skills)) save.player.skills[key] = 99;
  const original = structuredClone(save);
  const report = simulateAsianGames(save)!;
  expect(report.selected).toBe(true); expect(report.roster).toHaveLength(24);
  expect(report.roster.filter(player => player.wildcard).length).toBeLessThanOrEqual(3);
  expect(report.games).toHaveLength(22);
  expect(report.games.filter(game => game.stage === '조별리그')).toHaveLength(12);
  expect(report.games.filter(game => game.stage === '슈퍼라운드')).toHaveLength(4);
  expect(report.games.every(game => game.home !== game.away)).toBe(true);
  expect(new Set(report.games.map(game => game.id)).size).toBe(22);
  const appearance = role === 'HITTER' ? report.hitter : report.pitcher;
  expect(appearance?.g).toBeGreaterThan(0); expect(appearance?.g).toBeLessThanOrEqual(6);
  expect(save.league).toEqual(original.league); expect(save.rngState).toBe(original.rngState);
  expect(save.player.teamId).toBe(original.player.teamId); expect(save.player.skills).toEqual(original.player.skills);
  expect(save.seasons).toEqual(original.seasons); expect(save.contractService).toEqual(original.contractService);
  const replay = structuredClone(original); expect(simulateAsianGames(replay)).toEqual(report);
  const reputation = save.player.reputation;
  expect(simulateAsianGames(save)).toBe(report); expect(save.asianGames).toHaveLength(1);
  expect(save.player.reputation).toBe(reputation);
});
it('비대회 연도와 고교는 건너뛰고 낮은 성적·나이 제한은 미선발로 기록한다', () => {
  expect(isAsianGamesYear(2030)).toBe(true); expect(isAsianGamesYear(2031)).toBe(false);
  const school = createCareer({ name: '고교', role: 'HITTER', teamId: 'lg', hand: 'RIGHT', schoolId: SCHOOLS[0].id }, 2);
  expect(simulateAsianGames(school)).toBeNull(); expect(school.asianGames).toBeUndefined();
  const save = createCareer({ name: '경쟁', role: 'HITTER', teamId: 'lg', hand: 'RIGHT' }, 2);
  save.year = 2031; expect(simulateAsianGames(save)).toBeNull();
  save.year = 2030; save.player.age = 22;
  for (const key of Object.keys(save.player.skills)) save.player.skills[key] = 1;
  const report = simulateAsianGames(save)!;
  expect(report.selected).toBe(false); expect(report.hitter).toBeNull(); expect(report.reputationGain).toBe(0);
  save.year = 2034; save.player.age = 31;
  expect(simulateAsianGames(save)?.reason).toContain('연령');
});
